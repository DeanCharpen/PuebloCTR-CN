#!/usr/bin/env python3
"""PuebloCTR: the minimap's game-side tables, generated at build time from the game's own map screen
(src/Sscrn/ss_map.cpp of the CubeEvil4 tree): stageNo, areaNo, search, color, the room lists of each area, the area
files, the marks (goal, merchant, treasures, medallions), the doors - so the minimap follows the game's rules. The
result (port/whole/runtime/minimap_game.h) is not kept in the repository: it is the game's code.

    python3 tools/minimap_gen.py TREE
"""
import re
import sys

TREE = sys.argv[1].rstrip('/') + '/'
OUT = TREE + 'port/whole/runtime/minimap_game.h'


def cat(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def put(p, s):
    with open(p, 'w', encoding='utf-8') as f:
        f.write(s)


src = cat(TREE + 'src/Sscrn/ss_map.cpp')


def body(sig):
    i = src.index(sig + '\n{')
    j = src.index('\n}\n', i)
    return src[i + len(sig):j + 2]  # from "\n{" to "}\n"


def strip_comments(b):
    return '\n'.join(l for l in b.split('\n') if not l.strip().startswith('//'))


stage = strip_comments(body('int getStageNo()'))
area = strip_comments(body('int getAreaNo(u32 room)')).replace('getStageNo()', 'stageNo()')
search = strip_comments(body('MAP_DISP_FLAG* searchMapDispFlag(u16 room, MAP_DISP_FLAG* tbl, int n)'))
color = strip_comments(body('int mapColor(u16 room)'))
color = color.replace('getAreaNo(room)', 'areaNo(room)').replace('searchMapDispFlag(', 'search(')
color = color.replace('SubScreenWk.room_no', 'cur')
assert 'SubScreenWk' not in color and 'wk->' not in color

# the room lists
tbl = body('void mapTblInit(SUB_SCREEN* wk)')
cases = re.findall(r'((?:    case \d+:\n)+)        map_room_num = (mapDataInit_\w+)\(wk\);', tbl)
lists = {}
for _, fn in cases:
    b = body('int %s(SUB_SCREEN* wk)' % fn)
    lists[fn] = re.findall(r'MAP_ROOM\((0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\)', b)
files = re.findall(r'case (\d+):\n        sprintf\(name, "([^"]+)"\);', body('void mapAreaFilename(int area, char* name)'))

out = ['// Generated by tools/minimap_gen.py from src/Sscrn/ss_map.cpp at build time (the minimap on the 3DS\'s bottom',
       '// screen): the map screen\'s rules, nearly word for word, for the game\'s thread (runtime/cheats.cpp).',
       '#pragma once', '', 'namespace mm {', '',
       '// MAP_DISP_FLAG of ss_map.cpp: the stage flags of a room\'s display',
       'struct MAP_DISP_FLAG {', '    u16 room;', '    u16 pad;', '    u32 hide;', '    u32 open;', '    u32 clear;', '};', '',
       'struct Room {', '    u16 room;', '    u16 sub;  // the sub-file of the area\'s map_obj file', '};', '',
       '// getStageNo', 'static int stageNo()' + stage, '',
       '// getAreaNo', 'static int areaNo(u32 room)' + area, '',
       '// searchMapDispFlag', 'static MAP_DISP_FLAG* search(u16 room, MAP_DISP_FLAG* tbl, int n)' + search, '',
       '// mapColor: 0 the current room (`cur`), 1 visited, 2 open, 3 cleared, 4 not shown',
       'static int color(u16 room, u16 cur)' + color, '']
for fn, rooms in lists.items():
    out.append('static const Room k_%s[%d] = {' % (fn, len(rooms)))
    for k in range(0, len(rooms), 6):
        out.append('    ' + ' '.join('{%s, %s},' % r for r in rooms[k:k + 6]))
    out.append('};')
out.append('')
out.append('// mapTblInit: the rooms of an area (0 when none)')
out.append('static const Room* areaRooms(int area, int* n)\n{\n    switch (area) {')
for labels, fn in cases:
    out.append(labels.rstrip('\n'))
    out.append('        *n = %d;\n        return k_%s;' % (len(lists[fn]), fn))
out.append('    }\n    *n = 0;\n    return 0;\n}\n')
out.append('// mapAreaFilename: the area\'s file (as the game names it on the disc)')
out.append('static const char* areaFile(int area)\n{\n    switch (area) {')
for n, name in files:
    out.append('    case %s:\n        return "%s";' % (n, name))
out.append('    }\n    return 0;\n}\n')
# the marks (8.3b): which part of the goal model (markGoalPosition), of the merchant model (markMerchantPosition),
# whether the area has the models / the merchant is shown (mark_model_tbl, scf_check_merchant)
i = src.index('static const int mark_model_tbl[18][5] = {')
out.append('// mark_model_tbl: per area goal, merchant, treasure, coin, typewriter (the map_obj file holds that model)')
out.append(src[i:src.index('};', i) + 2])
out.append('')
g = strip_comments(body('int markGoalPosition(SUB_SCREEN* wk, Vec* pos)'))
g = g.replace('    SsMapWork* m = wk->map;\n', '').replace('    cParts* p;\n', '').replace('switch (m->area)', 'switch (area)')
g = g.replace('    p = m->pGoal->getPartsPtr(no);\n    *pos = p->pos;\n    return 1;', '    return no;')
assert 'wk' not in g and 'pos' not in g, g[-300:]
out.append('// markGoalPosition: the goal model\'s part (by the stage flags)')
out.append('static int goalPart(int area)' + g)
mm_ = strip_comments(body('int markMerchantPosition(SUB_SCREEN* wk, int no, Vec* pos)'))
mm_ = mm_.replace('    SsMapWork* m = wk->map;\n', '').replace('    cParts* p;\n', '').replace('    int ret;\n', '')
mm_ = mm_.replace('m->area == 1', 'area == 1')
mm_ = mm_.replace('            p = m->pMerchant->getPartsPtr(tbl[idx * 2 + 1]);\n            *pos = p->pos;\n            return 1;', '            return tbl[idx * 2 + 1];')
mm_ = mm_.replace('            return 0;\n        }\n    } else {', '            return -1;\n        }\n    } else {')
mm_ = mm_.replace('''        cModel* mdl = m->pMerchant;

        if (no < mdl->nParts) {
            p = mdl->getPartsPtr(no);
            *pos = p->pos;
            return 1;
        }
        return 0;''', '''        return no < nParts ? no : -1;''')
assert 'wk' not in mm_ and 'pos' not in mm_ and 'mdl' not in mm_, mm_[-500:]
out.append('// markMerchantPosition: merchant mark `no`\'s part of the model (-1 none)')
out.append('static int merchantPart(int area, int no, int nParts)' + mm_)
sc = strip_comments(body('int scf_check_merchant()'))
sc = sc.replace('    SsMapWork* m = SubScreenWk.map;\n\n', '').replace('m->area', 'area')
assert 'SubScreenWk' not in sc, sc
out.append('// scf_check_merchant: the merchant marks shown')
out.append('static int merchantShown(int area)' + sc)
# the treasures and the blue medallions (8.3d): scf_check_treasure (the treasure map owned), markTreasureExist (still
# in place; the index guarded: the game asks only below the model's parts), scf_check_submission (the request note /
# the mission started); the medallions themselves - checkSubMissionTarget (stage.cpp) on the game's thread
fb = strip_comments(body('static inline u32 flagBit(u32 tbl, u32 no)'))
out.append('// flagBit of ss_map.cpp (markTreasureExist\'s area 4)')
out.append('static inline u32 flagBit(u32 tbl, u32 no)' + fb)
st = strip_comments(body('int scf_check_treasure()'))
st = st.replace('    int area = SubScreenWk.map->area;\n\n', '')
assert 'SubScreenWk' not in st, st
out.append('// scf_check_treasure: the treasure marks shown')
out.append('static int treasureShown(int area)' + st)
te = strip_comments(body('int markTreasureExist(int no)')).replace('switch (SubScreenWk.map->area)', 'switch (area)')
te, n_ = re.subn(r'return (FlagChkVar|flagBit)\(\(u32\) pG->Item_flg, (\w+)\[no\]\) == 0;',
                 r'return no < (int) sizeof(\2) && \1((u32) pG->Item_flg, \2[no]) == 0;', te)
assert n_ == 10 and 'SubScreenWk' not in te, te[-400:]
out.append('// markTreasureExist: treasure `no` of the area still in place')
out.append('static int treasureLeft(int area, int no)' + te)
ss_ = strip_comments(body('int scf_check_submission()'))
ss_ = ss_.replace('    SsMapWork* m = SubScreenWk.map;\n\n', '').replace('m->area', 'area')
assert 'SubScreenWk' not in ss_, ss_
out.append('// scf_check_submission: the medallion marks shown')
out.append('static int coinShown(int area)' + ss_)
# the doors (8.3c): map_door_* / map_door_tbl as they are (doorModelInit / doorModelDisp)
out.append('// MapDoor of ss_map.cpp: the part of the doors\' model a door hangs on (-1: the model itself, not a door), its turn,')
out.append('// what opens it (1 a stage flag, 2 a door unlock flag), that flag, the key item')
out.append('struct MapDoor {\n    s8 parts;\n    u8 ang;\n    u8 flagType;\n    u8 flagNo;\n    u8 item;\n};\n')
out.append('struct MapDoorTbl {\n    MapDoor* p;\n    u8 n;\n    u8 pad[3];\n};\n')
for m_ in re.finditer(r'^MapDoor map_door_\w+\[\d+\] = \{.*?^\};', src, re.S | re.M):
    out.append('static ' + m_.group(0))
m_ = re.search(r'^MapDoorTbl map_door_tbl\[18\] = \{.*?^\};', src, re.S | re.M)
out.append('static ' + m_.group(0))
out.append('')
out.append('// doorModelDisp: a door\'s state: 1 open, 2 locked, 3 locked with its key carried')
out.append('''static int doorState(const MapDoor* e)
{
    int open;

    if (e->flagType == 1) {
        open = FlagChkVar((u32) &pG->Scenario_flg[0], e->flagNo) ? 1 : 0;
    } else if (e->flagType == 2) {
        open = FlagChkVar((u32) pG->Key_flg, e->flagNo) ? 1 : 0;
    } else {
        open = 1;
    }
    if (open) {
        return 1;
    }
    return ItemMgr.num(e->item) ? 3 : 2;
}''')
out.append('}  // namespace mm')
text = '\n'.join(out) + '\n'
# the retail discs' rules the game's patches 0129, 0141, 0209 add to the map screen (the source read here is without
# the patches)
GAME_PAIRS = [
    ("""#pragma once

namespace mm {
""",
     """#pragma once

// (8.3f) the retail discs' switches (runtime/dvd.cpp), as the game's patches 0129, 0141, 0209 use them
extern "C" int re4_disc_retail(void), re4_disc_retail_us(void), re4_disc_retail_eu(void), re4_disc_retail_jp(void);

namespace mm {
"""),
    ("""    int st1[10] = {0, 0x11, 0x12, 0x13, 0x14, 0x15, 0x2C, 0x17, 0x0B, 0x2E};
""",
     """    int st1[10] = {0, 0x11, 0x12, 0x13, 0x14, 0x15, 0x2C, 0x17, 0x0B, 0x2E};
    int st1r[12] = {0, 0x11, 0x12, 0x13, 0x14, 0x15, 0x2C, 0xA7, 0xA8, 0x17, 0x0B, 0x2E};  // (8.3f, patch 0209: retail)
    int st3er[7] = {0, 0xB8, 0x4F, 0x50, 0x51, 0x52, 0x53};  // (8.3f, patch 0209: European, Japanese, Korean)
"""),
    ("""    case 1:
        tbl = st1;
        n = 10;
        break;
""",
     """    case 1:
        tbl = st1;
        n = 10;
        if (re4_disc_retail()) {  // (8.3f, patch 0209)
            tbl = st1r;
            n = 12;
        }
        break;
"""),
    ("""    case 9:
        tbl = st3e;
        n = 6;
        break;
""",
     """    case 9:
        tbl = st3e;
        n = 6;
        if (re4_disc_retail() && !re4_disc_retail_us()) {  // (8.3f, patch 0209)
            tbl = st3er;
            n = 7;
        }
        break;
"""),
    ("""    } else {
        return no < nParts ? no : -1;
    }
}
""",
     """    } else {
        // (8.3f, patch 0129) the retail discs' castle merchant: mark 2 hidden once he moved, mark 7 before
        if (area == 2 && re4_disc_retail() && (ScfFlagChk(pG, SCF_R204_MERCHANT_MOVE) ? no == 2 : no == 7)) {
            return -1;
        }
        return no < nParts ? no : -1;
    }
}
"""),
    ("""// mapAreaFilename: the area's file (as the game names it on the disc)
static const char* areaFile(int area)
{""",
     """// mapAreaFilename: the area's file (as the game names it on the disc)
static const char* areaFileDisc(int area)
{"""),
    ("""// mark_model_tbl: per area goal, merchant, treasure, coin, typewriter (the map_obj file holds that model)
""",
     """// (8.3f, patch 0141) on Easy (game_country 0) the European discs' map objects are in SS/Esy, the Japanese ones in
// SS/Jpn; the names kept per area (the panel's thread reads the pointer)
static const char* areaFile(int area)
{
    const char* name = areaFileDisc(area);
    static char easy[18][24];
    if (!name || area < 0 || area >= 18 || pG->game_country != 0 || !(re4_disc_retail_eu() || re4_disc_retail_jp())) {
        return name;
    }
    char* e = easy[area];
    snprintf(e, sizeof(easy[0]), "%s", name);
    memcpy(e + 3, re4_disc_retail_eu() ? "esy" : "jpn", 3);
    return e;
}

// mark_model_tbl: per area goal, merchant, treasure, coin, typewriter (the map_obj file holds that model)
"""),
]
for old, new in GAME_PAIRS:
    assert text.count(old) == 1, old[:80]
    text = text.replace(old, new)
put(OUT, text)
print('ok: %d areas with lists, %d files, %d lines' % (len(cases), len(files), text.count('\n')))
